const fs = require('fs');
const path = require('path');
const { withDangerousMod, withAndroidManifest, withMainActivity, withMainApplication } = require('@expo/config-plugins');

// Adds an Android Quick Settings tile ("Mediscan QR") that launches MainActivity over the lock
// screen without unlocking it, landing on the /quick-scan route. The decoded medical data itself
// stays behind expo-local-authentication inside that route — this plugin only wires the native
// tile + the lock-screen display flags, not the auth gate.

const PACKAGE_PATH = 'com/application/mediscanmobile';
const PACKAGE_NAME = 'com.application.mediscanmobile';
const ROUTE_EXTRA = 'qr_scanner_tile_route';
const ROUTE_VALUE = 'quick-scan';
const EVENT_NAME = 'QrScannerTileRoute';

const TILE_SERVICE_KT = `package ${PACKAGE_NAME}

import android.app.PendingIntent
import android.content.Intent
import android.graphics.drawable.Icon
import android.os.Build
import android.service.quicksettings.Tile
import android.service.quicksettings.TileService

// @generated by plugins/withQrScannerTile.js — do not hand-edit, changes are overwritten on prebuild.
class QrScannerTileService : TileService() {
  override fun onStartListening() {
    super.onStartListening()
    qsTile?.apply {
      label = "Mediscan QR"
      icon = Icon.createWithResource(this@QrScannerTileService, R.drawable.qr_scanner_tile_icon)
      state = Tile.STATE_ACTIVE
      updateTile()
    }
  }

  override fun onClick() {
    super.onClick()
    val intent = Intent(this, MainActivity::class.java).apply {
      flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP or Intent.FLAG_ACTIVITY_SINGLE_TOP
      putExtra("${ROUTE_EXTRA}", "${ROUTE_VALUE}")
    }
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
      val pendingIntent = PendingIntent.getActivity(
        this, 0, intent, PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT,
      )
      startActivityAndCollapse(pendingIntent)
    } else {
      @Suppress("DEPRECATION")
      startActivityAndCollapse(intent)
    }
  }
}
`;

const TILE_MODULE_KT = `package ${PACKAGE_NAME}

import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod
import com.facebook.react.modules.core.DeviceEventManagerModule

// @generated by plugins/withQrScannerTile.js — do not hand-edit, changes are overwritten on prebuild.
// Lets JS clear the lock-screen display flags MainActivity sets when launched from the QS tile,
// once the quick-scan route is left, so the rest of the app never renders over the lock screen.
// Also bridges the tile's pending route to JS: consumePendingRoute() covers cold start (JS mounts
// after MainActivity.onCreate already recorded it), the "${EVENT_NAME}" event covers warm start
// (onNewIntent fires while JS is already running).
class QrScannerTileModule(reactContext: ReactApplicationContext) : ReactContextBaseJavaModule(reactContext) {
  override fun getName() = "QrScannerTileModule"

  @ReactMethod
  fun clearLockScreenFlags() {
    (reactApplicationContext.currentActivity as? MainActivity)?.clearQuickScanLockScreenFlags()
  }

  @ReactMethod
  fun consumePendingRoute(promise: Promise) {
    val route = (reactApplicationContext.currentActivity as? MainActivity)?.consumePendingQuickScanRoute()
    promise.resolve(route)
  }

  // Required by NativeEventEmitter's JS-side contract even though events are emitted directly via
  // RCTDeviceEventEmitter below — without these, RN warns "NativeEventEmitter... without the
  // required addListener/removeListeners method".
  @ReactMethod
  fun addListener(eventName: String) {}

  @ReactMethod
  fun removeListeners(count: Int) {}

  companion object {
    fun emitRoute(reactContext: ReactContext, route: String) {
      reactContext
        .getJSModule(DeviceEventManagerModule.RCTDeviceEventEmitter::class.java)
        .emit("${EVENT_NAME}", route)
    }
  }
}
`;

const TILE_PACKAGE_KT = `package ${PACKAGE_NAME}

import com.facebook.react.ReactPackage
import com.facebook.react.bridge.NativeModule
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.uimanager.ViewManager

// @generated by plugins/withQrScannerTile.js — do not hand-edit, changes are overwritten on prebuild.
class QrScannerTilePackage : ReactPackage {
  override fun createNativeModules(reactContext: ReactApplicationContext): List<NativeModule> =
    listOf(QrScannerTileModule(reactContext))

  override fun createViewManagers(reactContext: ReactApplicationContext): List<ViewManager<*, *>> = emptyList()
}
`;

const MAIN_ACTIVITY_IMPORTS = `import android.content.Intent
import com.facebook.react.ReactApplication`;

const MAIN_ACTIVITY_HANDLER = `
  private var pendingQuickScanRoute: String? = null

  /** Called from JS (QrScannerTileModule) once it has mounted, to pick up a cold-start tile launch. */
  fun consumePendingQuickScanRoute(): String? {
    val route = pendingQuickScanRoute
    pendingQuickScanRoute = null
    return route
  }

  private fun handleQuickScanIntent(intent: Intent?) {
    if (intent?.getStringExtra("${ROUTE_EXTRA}") != "${ROUTE_VALUE}") return
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O_MR1) {
      setShowWhenLocked(true)
      setTurnScreenOn(true)
    }
    pendingQuickScanRoute = "${ROUTE_VALUE}"
    val reactContext = (application as? ReactApplication)?.reactHost?.currentReactContext
    if (reactContext != null) {
      pendingQuickScanRoute = null
      QrScannerTileModule.emitRoute(reactContext, "${ROUTE_VALUE}")
    }
  }

  /** Called from JS (QrScannerTileModule) once the quick-scan route is left post-auth. */
  fun clearQuickScanLockScreenFlags() {
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O_MR1) {
      setShowWhenLocked(false)
      setTurnScreenOn(false)
    }
  }

  override fun onNewIntent(intent: Intent) {
    super.onNewIntent(intent)
    handleQuickScanIntent(intent)
  }
`;

function withQrScannerTileNativeFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const javaDir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/java', PACKAGE_PATH);
      fs.mkdirSync(javaDir, { recursive: true });
      fs.writeFileSync(path.join(javaDir, 'QrScannerTileService.kt'), TILE_SERVICE_KT);
      fs.writeFileSync(path.join(javaDir, 'QrScannerTileModule.kt'), TILE_MODULE_KT);
      fs.writeFileSync(path.join(javaDir, 'QrScannerTilePackage.kt'), TILE_PACKAGE_KT);

      const drawableDir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/res/drawable');
      fs.mkdirSync(drawableDir, { recursive: true });
      const monochromeSource = path.join(config.modRequest.projectRoot, 'assets/images/android-icon-monochrome.png');
      const iconDest = path.join(drawableDir, 'qr_scanner_tile_icon.png');
      if (fs.existsSync(monochromeSource)) {
        fs.copyFileSync(monochromeSource, iconDest);
      }

      return config;
    },
  ]);
}

function withQrScannerTileManifest(config) {
  return withAndroidManifest(config, (config) => {
    const application = config.modResults.manifest.application[0];
    const alreadyRegistered = (application.service ?? []).some(
      (service) => service.$['android:name'] === '.QrScannerTileService',
    );
    if (!alreadyRegistered) {
      application.service = application.service ?? [];
      application.service.push({
        $: {
          'android:name': '.QrScannerTileService',
          'android:label': 'Mediscan QR',
          'android:icon': '@drawable/qr_scanner_tile_icon',
          'android:permission': 'android.permission.BIND_QUICK_SETTINGS_TILE',
          'android:exported': 'true',
        },
        'intent-filter': [
          {
            action: [{ $: { 'android:name': 'android.service.quicksettings.action.QS_TILE' } }],
          },
        ],
      });
    }
    return config;
  });
}

function withQrScannerTileMainActivity(config) {
  return withMainActivity(config, (config) => {
    if (config.modResults.language !== 'kt') {
      throw new Error('withQrScannerTile only supports a Kotlin MainActivity');
    }
    let contents = config.modResults.contents;

    if (!contents.includes('handleQuickScanIntent')) {
      if (!contents.includes('import android.content.Intent')) {
        contents = contents.replace('import android.os.Bundle', `import android.os.Bundle\n${MAIN_ACTIVITY_IMPORTS}`);
      }
      contents = contents.replace(
        /super\.onCreate\(null\)\n/,
        `super.onCreate(null)\n    handleQuickScanIntent(intent)\n`,
      );
      contents = contents.replace(
        /override fun getMainComponentName\(\): String = "main"/,
        (match) => `${match}\n${MAIN_ACTIVITY_HANDLER}`,
      );
    }

    config.modResults.contents = contents;
    return config;
  });
}

function withQrScannerTileMainApplication(config) {
  return withMainApplication(config, (config) => {
    if (config.modResults.language !== 'kt') {
      throw new Error('withQrScannerTile only supports a Kotlin MainApplication');
    }
    if (!config.modResults.contents.includes('QrScannerTilePackage')) {
      config.modResults.contents = config.modResults.contents.replace(
        '// add(MyReactNativePackage())',
        '// add(MyReactNativePackage())\n          add(QrScannerTilePackage())',
      );
    }
    return config;
  });
}

module.exports = function withQrScannerTile(config) {
  config = withQrScannerTileNativeFiles(config);
  config = withQrScannerTileManifest(config);
  config = withQrScannerTileMainActivity(config);
  config = withQrScannerTileMainApplication(config);
  return config;
};
